//! No unused or misplaced dependencies
//!
//! Docs and examples: `rules/no-unused-deps/`.

use regex::Regex;

use crate::helpers::idioms;
use crate::rule::{Area, Context, Findings, Kind, Rule};
use crate::workspace::{is_test_path, DepKind, Dependency, Package, Workspace};

pub static RULE: Rule = Rule {
    id: "no-unused-deps",
    area: Area::DeadCode,
    title: "No unused or misplaced dependencies",
    kind: Kind::Code,
    clippy: &[],
    in_tests: false,
    check,
};

/// Where a dependency's crate is mentioned in the package's Rust code.
#[derive(Default, Clone, Copy)]
struct Uses {
    /// In library or binary code.
    shipped: bool,
    /// In `#[cfg(test)]` code, `tests/`, `benches/`, `examples/` or doc comments.
    tests: bool,
    /// In `build.rs`.
    build: bool,
}

fn check(cx: &Context, out: &mut Findings) {
    for package in cx.ws.packages() {
        // Component crates; tools, examples, benchmarks and test harnesses
        // are not shipped.
        if !package.dir.starts_with("components/")
            || package.dir.contains("bench")
            || idioms::is_generated(&package.manifest)
            || is_test_path(&format!("{}/", package.dir))
        {
            continue;
        }
        let Some(manifest) = cx.ws.file(&package.manifest) else {
            continue;
        };
        let ignored = machete_ignored(package);
        for dep in package.dependencies() {
            if dep.optional || ignored.contains(&dep.name) || dep.name.ends_with("-sys") {
                continue;
            }
            let Some(line) = declaration_line(&manifest.text, &dep) else {
                continue;
            };
            if documented(&manifest.text, line)
                || in_features(package, &dep.name)
                || mentioned_in_comment(&manifest.text, &dep.name)
            {
                continue;
            }
            let mut uses = Uses::default();
            for name in code_names(cx.ws, package, &dep) {
                uses.add(self::uses(cx.ws, package, &name));
            }
            // Code generated by `serde_derive` refers to the `serde` crate.
            if dep.name == "serde" && derives_serde(cx.ws, package) {
                uses.shipped = true;
            }
            // A dependency declared only to turn on features of a crate that
            // other dependencies use.
            let enables_features = manifest
                .line(line)
                .split_once("features")
                .is_some_and(|(before, _)| !before.ends_with("default-"));
            if dep.kind == DepKind::Normal && enables_features && !uses.any() {
                continue;
            }
            let message = match dep.kind {
                DepKind::Normal if !uses.any() => format!(
                    "`{}` is in [dependencies] but no Rust code in the crate uses it; remove it",
                    dep.name
                ),
                DepKind::Normal if !uses.shipped && !uses.build => format!(
                    "`{}` is only used by tests; move it to [dev-dependencies]",
                    dep.name
                ),
                DepKind::Build if !uses.build => format!(
                    "`{}` is in [build-dependencies] but build.rs does not use it; remove it",
                    dep.name
                ),
                DepKind::Dev if !uses.any() => format!(
                    "`{}` is in [dev-dependencies] but no test, bench or example uses it; remove it",
                    dep.name
                ),
                _ => continue,
            };
            out.add(&package.manifest, line, message);
        }
    }
}

/// The names code may use for a dependency: `error_support` for
/// `error-support`, `md5` for `md-5`, or the `[lib] name` of a path
/// dependency.
fn code_names(ws: &Workspace, package: &Package, dep: &Dependency) -> Vec<String> {
    let mut names = vec![dep.name.replace('-', "_"), dep.name.replace('-', "")];
    if let Some(path) = &dep.path {
        let dir = normalize(&format!("{}/{}", package.dir, path));
        if let Some(target) = ws.packages().iter().find(|p| p.dir == dir) {
            names.push(target.lib_name());
        }
    }
    names.dedup();
    names
}

/// Whether the package derives `Serialize`/`Deserialize`.
fn derives_serde(ws: &Workspace, package: &Package) -> bool {
    ws.package_files(package)
        .filter(|f| f.extension() == "rs")
        .filter_map(|f| ws.rust(&f.path))
        .any(|f| {
            crate::syntax::all_items(&f.ast).iter().any(|item| {
                let attrs = match item {
                    syn::Item::Struct(s) => &s.attrs,
                    syn::Item::Enum(e) => &e.attrs,
                    _ => return false,
                };
                crate::syntax::has_derive(attrs, "Serialize")
                    || crate::syntax::has_derive(attrs, "Deserialize")
            })
        })
}

fn normalize(path: &str) -> String {
    let mut parts: Vec<&str> = Vec::new();
    for part in path.split('/') {
        match part {
            "" | "." => {}
            ".." => {
                parts.pop();
            }
            p => parts.push(p),
        }
    }
    parts.join("/")
}

impl Uses {
    fn add(&mut self, other: Uses) {
        self.shipped |= other.shipped;
        self.tests |= other.tests;
        self.build |= other.build;
    }

    fn any(&self) -> bool {
        self.shipped || self.tests || self.build
    }
}

/// Where the crate `name` is referenced (`name::`, `use name`, `extern crate
/// name`) in the package's own Rust files.
fn uses(ws: &Workspace, package: &Package, name: &str) -> Uses {
    let re = Regex::new(&format!(
        r"(^|[^A-Za-z0-9_]){n}\s*::|\buse\s+{n}\b|\bextern\s+crate\s+{n}\b|\b{n}\s*!",
        n = regex::escape(name)
    ))
    .expect("valid regex");
    let build_script = package
        .package_field("build")
        .and_then(|b| b.as_str())
        .unwrap_or("build.rs")
        .trim_start_matches("./")
        .to_string();
    let mut uses = Uses::default();
    for file in ws.package_files(package) {
        if file.extension() != "rs" {
            continue;
        }
        let rel = file.path.strip_prefix(&package.dir).unwrap_or(&file.path);
        let is_build = rel.strip_prefix('/') == Some(build_script.as_str())
            || rel.starts_with("/build/");
        let rust = ws.rust(&file.path);
        for (n, line) in file.lines() {
            if !re.is_match(line) {
                continue;
            }
            let trimmed = line.trim_start();
            if is_build {
                uses.build = true;
            } else if is_test_path(&file.path)
                || rust.is_some_and(|r| r.in_test(n))
                || trimmed.starts_with("///")
                || trimmed.starts_with("//!")
            {
                uses.tests = true;
            } else {
                uses.shipped = true;
            }
        }
    }
    uses
}

/// The 1-based line declaring `dep` in its table of the manifest.
fn declaration_line(text: &str, dep: &Dependency) -> Option<usize> {
    let table = match dep.kind {
        DepKind::Normal => "[dependencies]",
        DepKind::Dev => "[dev-dependencies]",
        DepKind::Build => "[build-dependencies]",
    };
    let mut in_table = false;
    for (i, line) in text.lines().enumerate() {
        let t = line.trim();
        if t.starts_with('[') {
            in_table = t == table;
            continue;
        }
        if in_table {
            let key = t.split('=').next().unwrap_or("").trim().trim_matches('"');
            if key == dep.name {
                return Some(i + 1);
            }
        }
    }
    None
}

/// A comment line right above the declaration says why it is there
/// (`# Needed so that rusqlite builds with the bundled SQLite.`).
fn documented(text: &str, line: usize) -> bool {
    line >= 2
        && text
            .lines()
            .nth(line - 2)
            .is_some_and(|above| above.trim_start().starts_with('#'))
}

/// A `[features]` entry forwards to the dependency (`"nss-as/keydb"`,
/// `"dep:tempfile"`), so it must stay where it is.
fn in_features(package: &Package, name: &str) -> bool {
    let Some(features) = package.toml.get("features").and_then(|f| f.as_table()) else {
        return false;
    };
    features.values().filter_map(|v| v.as_array()).flatten().any(|v| {
        v.as_str().is_some_and(|f| {
            let f = f.strip_prefix("dep:").unwrap_or(f);
            let target = f.split('/').next().unwrap_or(f).trim_end_matches('?');
            target == name
        })
    })
}

/// The manifest discusses the dependency in a comment (`# Note: if set, we
/// will not use `glean-sym``): someone thought about it.
fn mentioned_in_comment(text: &str, name: &str) -> bool {
    text.lines().any(|l| {
        l.split_once('#')
            .is_some_and(|(before, comment)| !before.contains('"') && comment.contains(name))
    })
}

/// `[package.metadata.cargo-machete] ignored = [..]`.
fn machete_ignored(package: &Package) -> Vec<String> {
    package
        .toml
        .get("package")
        .and_then(|p| p.get("metadata"))
        .and_then(|m| m.get("cargo-machete"))
        .and_then(|m| m.get("ignored"))
        .and_then(|i| i.as_array())
        .map(|a| {
            a.iter()
                .filter_map(|v| v.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::RULE;
    use crate::testing::check;

    const MANIFEST: &str = "components/places/Cargo.toml";
    const HEADER: &str = "[package]\nname = \"places\"\nversion = \"0.1.0\"\n\n";
    const LIB: (&str, &str) = (
        "components/places/src/lib.rs",
        "use error_support::handle_error;\nuse sql_support::ConnExt;\npub fn parse(u: &str) -> url::Url { url::Url::parse(u).unwrap() }\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn t() { let _m = mockito::mock(\"GET\", \"/\"); env_logger::init(); }\n}\n",
    );

    fn manifest(body: &str) -> String {
        format!("{HEADER}{body}")
    }

    #[test]
    fn flags_dont() {
        let toml = manifest(include_str!("../../rules/no-unused-deps/dont.toml"));
        let found = check(&RULE, &[(MANIFEST, &toml), LIB]);
        let lines: Vec<usize> = found.iter().map(|f| f.line).collect();
        assert_eq!(lines, vec![7, 8], "{found:#?}");
        assert!(found[0].message.contains("`ffi-support` is in [dependencies]"));
        assert!(found[1].message.contains("`mockito` is only used by tests"));
    }

    #[test]
    fn accepts_do() {
        let toml = manifest(include_str!("../../rules/no-unused-deps/do.toml"));
        let found = check(&RULE, &[(MANIFEST, &toml), LIB]);
        assert!(found.is_empty(), "{found:#?}");
    }

    #[test]
    fn resolves_lib_names_and_skips_optional_documented_and_ignored_deps() {
        let toml = manifest(
            "[dependencies]\nnimbus-sdk = { path = \"../nimbus\" }\ntempfile = { version = \"3\", optional = true }\n# Needed so that rusqlite builds with the bundled SQLite.\nlibsqlite3-sys = \"0.30\"\nlog = \"0.4\"\nnss-as = { path = \"../nss\" }\nicu_normalizer = { version = \"2\", features = [\"compiled_data\"] }\n\n[features]\nkeydb = [\"nss-as/keydb\"]\n\n[package.metadata.cargo-machete]\nignored = [\"log\"]\n",
        );
        let found = check(
            &RULE,
            &[
                (MANIFEST, &toml),
                (
                    "components/nimbus/Cargo.toml",
                    "[package]\nname = \"nimbus-sdk\"\n[lib]\nname = \"nimbus\"\n",
                ),
                ("components/places/src/lib.rs", "use nimbus::Client;\n"),
            ],
        );
        assert!(found.is_empty(), "{found:#?}");
    }

    #[test]
    fn flags_unused_build_and_dev_dependencies() {
        let toml = manifest(
            "[dev-dependencies]\nmockall = \"0.13\"\n\n[build-dependencies]\nuniffi = { version = \"0.29\", features = [\"build\"] }\n",
        );
        let found = check(
            &RULE,
            &[(MANIFEST, &toml), ("components/places/src/lib.rs", "uniffi::setup_scaffolding!();\n")],
        );
        let lines: Vec<usize> = found.iter().map(|f| f.line).collect();
        assert_eq!(lines, vec![6, 9], "{found:#?}");
    }
}
